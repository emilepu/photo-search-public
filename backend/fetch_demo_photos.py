"""Downloads open-licensed demo photos from Wikimedia Commons into demo_photos/
and writes demo_photos/ATTRIBUTION.md for you.

Example (from the backend/ folder):
    python fetch_demo_photos.py --contact you@example.com

Wikimedia asks every script to say who it is, so --contact is required (email or GitHub URL).

Only photos with these licenses are kept: CC0, public domain, CC BY, CC BY-SA.

AFTERWARDS: look through the photos yourself and delete the ones you don't want
(wrong subject, people, drawings, bad quality). Then run

    python fetch_demo_photos.py --contact you@example.com --credits-only

to refresh the credits so they only list the photos that are left.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import time
from pathlib import Path

import requests

API = "https://commons.wikimedia.org/w/api.php"

# folder name -> search words. Edit freely.
TOPICS: dict[str, list[str]] = {
    "Birds": ["owl", "woodpecker", "capercaillie"],
    "Mammals": ["red deer", "roe deer", "red fox", "beaver"],
    "Plants": ["old oak tree", "fern", "moss"],
    "Fungi": ["fly agaric mushroom", "chanterelle"],
    "Reptiles": ["grass snake"],
    "Landscapes": ["beech forest", "river in forest", "autumn forest", "snowy forest"],
}

# CC0, public domain, CC BY, CC BY-SA. This deliberately rejects -NC and -ND.
ALLOWED_LICENSE = re.compile(r"^(cc0|public domain|pd[ -]|cc by(-sa)? \d)")
MIN_WIDTH = 1000


def is_allowed_license(short_name: str) -> bool:
    return bool(ALLOWED_LICENSE.match(short_name.strip().lower()))


def clean_text(value: str) -> str:
    """Wikimedia gives author names as HTML. Turn that into plain text."""
    text = html.unescape(re.sub(r"<[^>]+>", "", value))
    return re.sub(r"\s+", " ", text).replace("|", "/").strip()


def slugify(title: str) -> str:
    stem = Path(title).stem
    return re.sub(r"[^A-Za-z0-9._-]+", "_", stem).strip("_")[:70] + ".jpg"


def api_get(session, params: dict, headers: dict, retries: int = 3) -> dict:
    for attempt in range(retries):
        res = session.get(API, params=params, headers=headers, timeout=30)
        if res.status_code == 429 and attempt < retries - 1:   # asked to slow down
            time.sleep(5 * (attempt + 1))
            continue
        res.raise_for_status()
        return res.json()
    raise RuntimeError("unreachable")


def search_pages(session, term: str, headers: dict, limit: int) -> list[dict]:
    params = {
        "action": "query", "format": "json", "formatversion": "2",
        "generator": "search", "gsrsearch": f"{term} filetype:bitmap",
        "gsrnamespace": "6", "gsrlimit": str(limit),
        "prop": "imageinfo", "iiprop": "url|size|mime|extmetadata", "iiurlwidth": "1280",
        "iiextmetadatafilter": "LicenseShortName|Artist|Restrictions",
    }
    pages = api_get(session, params, headers).get("query", {}).get("pages", [])
    return sorted(pages, key=lambda p: p.get("index", 0))   # best search match first


def pick(pages: list[dict], how_many: int, seen: set[str]) -> list[dict]:
    """Keep the first `how_many` pages that are big JPEGs with an allowed license and a known author."""
    picked = []
    for p in pages:
        info = (p.get("imageinfo") or [None])[0]
        if not info or info.get("mime") != "image/jpeg" or info.get("width", 0) < MIN_WIDTH:
            continue
        meta = info.get("extmetadata") or {}
        license_name = clean_text(meta.get("LicenseShortName", {}).get("value", ""))
        if not is_allowed_license(license_name):
            continue
        if clean_text(meta.get("Restrictions", {}).get("value", "")):
            continue   # e.g. trademark or personality-rights notes
        author = clean_text(meta.get("Artist", {}).get("value", ""))
        if not author and license_name.lower().startswith("cc by"):
            continue   # CC BY needs a credit, so we need a name
        title = p["title"].removeprefix("File:")
        if title in seen:
            continue
        seen.add(title)
        picked.append({
            "title": title,
            "author": author or "Unknown",
            "license": license_name,
            "url": info.get("descriptionurl", ""),
            "download": info.get("thumburl") or info["url"],
        })
        if len(picked) == how_many:
            break
    return picked


def write_attribution(out_dir: Path, credits: list[dict]) -> int:
    rows = [c for c in credits if (out_dir / c["file"]).exists()]   # only photos that are still there
    lines = [
        "# Demo photo credits",
        "",
        "All photos come from [Wikimedia Commons](https://commons.wikimedia.org) and are licensed",
        "CC0, public domain, CC BY or CC BY-SA. This file was generated by `backend/fetch_demo_photos.py`.",
        "",
        "| File | Title | Author | License | Source |",
        "|---|---|---|---|---|",
    ]
    for c in sorted(rows, key=lambda c: c["file"]):
        lines.append(f"| {c['file']} | {c['title']} | {c['author']} | {c['license']} | {c['url']} |")
    (out_dir / "ATTRIBUTION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(rows)


def run(out_dir: Path, contact: str, per_term: int = 4, topics: dict[str, list[str]] | None = None,
        credits_only: bool = False, session=None, pause: float = 1.0) -> int:
    topics = topics or TOPICS
    out_dir.mkdir(parents=True, exist_ok=True)
    credits_file = out_dir / "credits.json"
    credits: list[dict] = json.loads(credits_file.read_text(encoding="utf-8")) if credits_file.exists() else []

    if not credits_only:
        session = session or requests.Session()
        headers = {"User-Agent": f"ForestPhotoSearchDemo/0.1 ({contact})"}
        seen = {c["title"] for c in credits}
        done_terms = {c.get("term") for c in credits}
        for folder, terms in topics.items():
            for term in terms:
                if term in done_terms:
                    print(f"Skipping '{term}': already downloaded")
                    continue
                print(f"Searching: {term}")
                pages = search_pages(session, term, headers, limit=per_term * 6)
                time.sleep(pause)
                for item in pick(pages, per_term, seen):
                    rel = f"{folder}/{slugify(item['title'])}"
                    dest = out_dir / rel
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    res = session.get(item["download"], headers=headers, timeout=60)
                    res.raise_for_status()
                    dest.write_bytes(res.content)
                    credits.append({"file": rel, "term": term,
                                    **{k: item[k] for k in ("title", "author", "license", "url")}})
                    print(f"  saved {rel}  ({item['license']}, {item['author'][:30]})")
                    time.sleep(pause)
        credits_file.write_text(json.dumps(credits, indent=2, ensure_ascii=False), encoding="utf-8")

    return write_attribution(out_dir, credits)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--contact", required=True, help="your email or GitHub URL (Wikimedia asks for this)")
    ap.add_argument("--out", type=Path, default=Path(__file__).parent.parent / "demo_photos")
    ap.add_argument("--per-term", type=int, default=4, help="photos per search word (default 4)")
    ap.add_argument("--credits-only", action="store_true", help="only refresh ATTRIBUTION.md")
    args = ap.parse_args()
    n = run(args.out, args.contact, args.per_term, credits_only=args.credits_only)
    print(f"Done. {n} photos listed in {args.out / 'ATTRIBUTION.md'}")
    print("Now look through the photos and delete any you don't want, then run again with --credits-only.")
